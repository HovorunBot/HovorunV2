"""Utilities for reading project version and parsing user-facing CHANGES.md and technical CHANGELOG.md."""

import logging
import os
import re
from importlib.metadata import PackageNotFoundError
from importlib.metadata import version as pkg_version
from pathlib import Path
from typing import Final

logger = logging.getLogger(__name__)

DEFAULT_VERSION: Final[str] = "0.0.0"
CLIENT_NOTES_FILENAME: Final[str] = "CHANGES.md"
TECHNICAL_CHANGELOG_FILENAME: Final[str] = "CHANGELOG.md"

SECTION_SPLIT_PATTERN: Final[re.Pattern[str]] = re.compile(r"^##\s+", flags=re.MULTILINE)
VERSION_HEADER_PATTERN: Final[re.Pattern[str]] = re.compile(r"v?(\d+\.\d+\.\d+)")

# Technical scopes filtered out from fallback changelog broadcast
INTERNAL_SCOPES: Final[set[str]] = {
    "build",
    "chore",
    "ci",
    "deps",
    "infra",
    "release",
    "test",
    "tests",
    "versioning",
}


def parse_version(version: str) -> tuple[int, ...]:
    """Convert version string to a comparable tuple of integers."""
    clean_version = version.lstrip("v").split("-")[0]
    parts = clean_version.split(".")
    parsed = [int(match.group()) for part in parts if (match := re.search(r"\d+", part))]
    return tuple(parsed) or (0, 0, 0)


def get_current_version() -> str:
    """Read current project version from environment, package metadata, pyproject, or fallback."""
    if env_ver := os.environ.get("APP_VERSION"):
        return env_ver.lstrip("v")

    try:
        return pkg_version("hovorunv2").lstrip("v")
    except PackageNotFoundError:
        pass

    project_version = _version_from_pyproject()
    return project_version if project_version is not None else DEFAULT_VERSION


def _version_from_pyproject() -> str | None:
    """Read the fallback project version when package metadata is unavailable."""
    pyproject_path = Path(__file__).resolve().parents[3] / "pyproject.toml"
    if not pyproject_path.exists():
        return None
    try:
        for line in pyproject_path.read_text(encoding="utf-8").splitlines():
            clean_line = line.strip()
            if clean_line.startswith("version = "):
                return clean_line.split("=")[1].strip().strip('"').strip("'").lstrip("v")
    except Exception as exc:
        logger.debug("Failed to read pyproject.toml: %s", exc)
    return None


def _find_file_in_project(filename: str) -> Path | None:
    """Locate file across common locations (repo root, app dir, working dir)."""
    candidates = [
        Path(__file__).resolve().parents[3] / filename,
        Path.cwd() / filename,
        Path("/app") / filename,
    ]
    for path in candidates:
        if path.exists():
            return path
    return None


def get_client_changelog_path() -> Path | None:
    """Locate client-facing CHANGES.md."""
    return _find_file_in_project(CLIENT_NOTES_FILENAME)


def get_technical_changelog_path() -> Path | None:
    """Locate developer CHANGELOG.md generated by Commitizen."""
    return _find_file_in_project(TECHNICAL_CHANGELOG_FILENAME)


def format_markdown_for_telegram(text: str) -> str:
    """Format markdown text into clean Telegram HTML."""
    lines: list[str] = []
    for raw_line in text.splitlines():
        line = raw_line.rstrip()
        # Convert markdown bullet prefixes (* or -) to bullet character •
        line = re.sub(r"^\s*[\*\-]\s+", "• ", line)
        # Convert **bold** to <b>bold</b>
        line = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", line)
        # Convert `code` to <code>code</code>
        line = re.sub(r"`([^`]+)`", r"<code>\1</code>", line)
        lines.append(line)
    return "\n".join(lines).strip()


def extract_release_notes(changelog_content: str, last_version: str, current_version: str) -> str | None:
    """Extract release notes from markdown text between last_version and current_version."""
    clean_curr = parse_version(current_version)
    clean_last = parse_version(last_version)
    if clean_curr <= clean_last:
        return None

    sections = SECTION_SPLIT_PATTERN.split(changelog_content)
    matching_notes: list[str] = []

    for section in sections:
        notes = _release_section_notes(section, clean_last, clean_curr)
        if notes is not None:
            matching_notes.append(notes)

    return "\n\n".join(matching_notes) if matching_notes else None


def _release_section_notes(section: str, last: tuple[int, ...], current: tuple[int, ...]) -> str | None:
    """Return a nonempty section body only when its version falls in the requested range."""
    clean_section = section.strip()
    if not clean_section:
        return None
    first_line = clean_section.splitlines()[0]
    match = VERSION_HEADER_PATTERN.search(first_line)
    if not match:
        return None
    version = parse_version(match.group(1))
    if not last < version <= current:
        return None
    cleaned_body = "\n".join(clean_section.splitlines()[1:]).strip()
    return cleaned_body or None


def extract_fallback_notes(technical_content: str, last_version: str, current_version: str) -> str | None:
    """Extract and filter user-facing entries from technical CHANGELOG.md as fallback."""
    raw_notes = extract_release_notes(technical_content, last_version, current_version)
    if not raw_notes:
        return None

    user_facing_lines: list[str] = []
    for raw_line in raw_notes.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("###"):
            continue

        # Match commitizen format: - **scope**: description or - description
        scope_match = re.match(r"^-\s+\*\*(?P<scope>[^*]+)\*\*:\s*(?P<desc>.+)$", line)
        if scope_match:
            scope = scope_match.group("scope").strip().lower()
            if scope in INTERNAL_SCOPES:
                continue
            desc = scope_match.group("desc").strip()
            formatted_desc = desc[0].upper() + desc[1:] if desc else ""
            formatted_scope = scope.replace("_", " ").title()
            user_facing_lines.append(f"• <b>{formatted_scope}:</b> {formatted_desc}")
            continue

        simple_match = re.match(r"^-\s+(?P<desc>.+)$", line)
        if simple_match:
            desc = simple_match.group("desc").strip()
            formatted_desc = desc[0].upper() + desc[1:] if desc else ""
            user_facing_lines.append(f"• {formatted_desc}")

    return "\n".join(user_facing_lines) if user_facing_lines else None


def get_changelog_updates(last_version: str, current_version: str) -> str | None:
    """Extract formatted user-facing release notes between last_version and current_version.

    Prioritizes curated client notes from CHANGES.md, falling back to filtered CHANGELOG.md.
    """
    # 1. Primary: Curated client notes in CHANGES.md
    if client_path := get_client_changelog_path():
        try:
            content = client_path.read_text(encoding="utf-8")
            if notes := extract_release_notes(content, last_version, current_version):
                return format_markdown_for_telegram(notes)
        except Exception as exc:
            logger.warning("Failed to read client notes from %s: %s", client_path, exc)

    # 2. Fallback: Filtered technical notes from CHANGELOG.md
    if tech_path := get_technical_changelog_path():
        try:
            content = tech_path.read_text(encoding="utf-8")
            if fallback := extract_fallback_notes(content, last_version, current_version):
                return fallback
        except Exception as exc:
            logger.warning("Failed to read technical changelog from %s: %s", tech_path, exc)

    logger.warning("No release notes found between %s and %s", last_version, current_version)
    return None
